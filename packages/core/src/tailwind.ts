import { getBreakpoints } from './breakpoints.js';
import { tokenPathToCssVarName } from './css-vars.js';
import { escapeCssVarNameSegment } from './css-emit.js';
import type { TokenMap } from './types.js';

/** Motif scales and the Tailwind v4 theme namespaces that read them. */
const NAMESPACES: Readonly<Record<string, string>> = {
  colors: 'color',
  space: 'spacing',
  sizes: 'container',
  radii: 'radius',
  fontSizes: 'text',
  fontWeights: 'font-weight',
  fontFamilies: 'font',
  lineHeights: 'leading',
  letterSpacings: 'tracking',
  shadows: 'shadow',
  easings: 'ease',
};

export interface TailwindThemeOptions {
  /**
   * Clear Tailwind's own values in each namespace motif fills (`--color-*: initial`), so only the
   * motif tokens generate utilities. Default `false`, which keeps both.
   */
  readonly replace?: boolean;
  /** Add `--breakpoint-*` from motif's breakpoints. Default `true`. */
  readonly breakpoints?: boolean;
}

/**
 * A Tailwind v4 `@theme inline` block that points Tailwind's theme at motif's token variables:
 * `--color-action-primary-bg: var(--colors-action-primary-bg)`, so `bg-action-primary-bg` paints
 * the motif token. `inline` makes each utility read the motif variable where it's used, so a
 * `data-theme` switch, nested sub-themes included, reaches Tailwind utilities too.
 *
 * Only the tokens' names come from `tokens`; their values come from the variables motif's
 * `ThemeProvider` sets, so one block serves every theme with the same token names.
 *
 * @example
 * ```ts
 * import { writeFileSync } from 'node:fs';
 * import { toTailwindTheme } from '@usemotif/core/tailwind';
 * import { lightTheme } from '@usemotif/tokens';
 *
 * writeFileSync('src/motif-theme.css', toTailwindTheme(lightTheme.tokens));
 * // then, in your CSS: @import "tailwindcss"; @import "./motif-theme.css";
 * ```
 */
export function toTailwindTheme(tokens: TokenMap, options: TailwindThemeOptions = {}): string {
  const lines: string[] = [];
  for (const [scale, namespace] of Object.entries(NAMESPACES)) {
    const node = tokens[scale];
    if (node === undefined || typeof node !== 'object') continue;
    if (options.replace === true) lines.push(`  --${namespace}-*: initial;`);
    const walk = (value: unknown, path: string[]): void => {
      if (typeof value === 'object' && value !== null) {
        for (const [key, child] of Object.entries(value)) walk(child, [...path, key]);
        return;
      }
      const name = `--${namespace}-${path.map(escapeCssVarNameSegment).join('-')}`;
      lines.push(`  ${name}: var(${tokenPathToCssVarName(scale, path)});`);
    };
    walk(node, []);
  }
  if (options.breakpoints !== false) {
    if (options.replace === true) lines.push('  --breakpoint-*: initial;');
    for (const [name, width] of Object.entries(getBreakpoints())) {
      lines.push(`  --breakpoint-${name}: ${width}px;`);
    }
  }
  return `/* Generated by @usemotif/core/tailwind: Tailwind reads motif's token variables. */\n@theme inline {\n${lines.join('\n')}\n}\n`;
}
